create or replace function private.notify_group_message()
returns trigger language plpgsql security definer set search_path='' as $$
declare gname text;
begin
 select name into gname from public.groups where id=new.group_id;
 insert into public.notifications(user_id,notification_type,title,body,href,source_id)
 select gm.user_id,'group_message',coalesce(gname,'رسالة جروب'),left(new.body,180),'/chats/'||new.group_id::text,new.id from public.group_members gm join public.profiles p on p.id=gm.user_id where gm.group_id=new.group_id and gm.user_id<>new.sender_id and p.role='member' and p.is_active=true on conflict do nothing;
 return new;
end; $$;
