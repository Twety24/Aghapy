create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists public.notifications (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.profiles(id) on delete cascade,
 notification_type text not null check(notification_type in ('message','daily_verse','meeting','photo','group_message')),
 title text not null,
 body text not null default '',
 href text not null default '/dashboard',
 source_id uuid,
 daily_verse_id uuid,
 created_at timestamptz not null default now(),
 read_at timestamptz,
 dismissed_at timestamptz
);
create index if not exists notifications_user_created_idx on public.notifications(user_id,created_at desc);
create unique index if not exists notifications_user_type_source_uidx on public.notifications(user_id,notification_type,source_id) where source_id is not null;
alter table public.notifications enable row level security;
drop policy if exists "notifications read own" on public.notifications;
create policy "notifications read own" on public.notifications for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists "notifications update own" on public.notifications;
create policy "notifications update own" on public.notifications for update to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
drop policy if exists "notifications delete own" on public.notifications;
create policy "notifications delete own" on public.notifications for delete to authenticated using(user_id=(select auth.uid()));
grant select,delete on public.notifications to authenticated;
 grant update(read_at,dismissed_at) on public.notifications to authenticated;

create table if not exists public.daily_verse_library (
 id bigint generated by default as identity primary key,
 reference text not null,
 verse_text text not null,
 created_at timestamptz not null default now(),
 unique(reference,verse_text)
);
alter table public.daily_verse_library enable row level security;
drop policy if exists "daily verse library read" on public.daily_verse_library;
create policy "daily verse library read" on public.daily_verse_library for select to authenticated using(true);
grant select on public.daily_verse_library to authenticated;

create table if not exists public.daily_verses (
 id uuid primary key default gen_random_uuid(),
 library_id bigint not null references public.daily_verse_library(id),
 verse_date date not null unique,
 reference text not null,
 verse_text text not null,
 created_at timestamptz not null default now()
);
alter table public.daily_verses enable row level security;
drop policy if exists "daily verses read" on public.daily_verses;
create policy "daily verses read" on public.daily_verses for select to authenticated using(true);
grant select on public.daily_verses to authenticated;

create table if not exists public.daily_verse_saves (
 user_id uuid not null references public.profiles(id) on delete cascade,
 verse_id uuid not null references public.daily_verses(id) on delete cascade,
 saved_at timestamptz not null default now(),
 primary key(user_id,verse_id)
);
alter table public.daily_verse_saves enable row level security;
drop policy if exists "daily verse saves read own" on public.daily_verse_saves;
create policy "daily verse saves read own" on public.daily_verse_saves for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists "daily verse saves insert own" on public.daily_verse_saves;
create policy "daily verse saves insert own" on public.daily_verse_saves for insert to authenticated with check(user_id=(select auth.uid()));
drop policy if exists "daily verse saves delete own" on public.daily_verse_saves;
create policy "daily verse saves delete own" on public.daily_verse_saves for delete to authenticated using(user_id=(select auth.uid()));
grant select,insert,delete on public.daily_verse_saves to authenticated;

alter table public.messages add column if not exists daily_verse_id uuid references public.daily_verses(id);
do $ begin if not exists(select 1 from pg_constraint where conname='notifications_daily_verse_id_fkey' and conrelid='public.notifications'::regclass) then alter table public.notifications add constraint notifications_daily_verse_id_fkey foreign key(daily_verse_id) references public.daily_verses(id) on delete cascade; end if; end $;
create index if not exists messages_daily_verse_idx on public.messages(daily_verse_id) where daily_verse_id is not null;

