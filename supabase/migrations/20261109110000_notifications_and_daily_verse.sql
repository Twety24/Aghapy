create or replace function private.create_user_notification(p_user_id uuid,p_type text,p_title text,p_body text,p_href text,p_source_id uuid default null,p_daily_verse_id uuid default null)
returns void language plpgsql security definer set search_path='' as $$
begin
 if p_user_id is null then return; end if;
 insert into public.notifications(user_id,notification_type,title,body,href,source_id,daily_verse_id)
 values(p_user_id,p_type,p_title,coalesce(p_body,''),coalesce(p_href,'/dashboard'),p_source_id,p_daily_verse_id)
 on conflict do nothing;
end; $$;
revoke all on function private.create_user_notification(uuid,text,text,text,text,uuid,uuid) from public,anon,authenticated;

create or replace function private.notify_message_recipient()
returns trigger language plpgsql security definer set search_path='' as $$
declare m record;
begin
 select id,title,body,daily_verse_id into m from public.messages where id=new.message_id;
 if not found then return new; end if;
 perform private.create_user_notification(new.user_id,case when m.daily_verse_id is null then 'message' else 'daily_verse' end,case when m.daily_verse_id is null then m.title else 'آية اليوم' end,case when m.daily_verse_id is null then left(m.body,180) else 'آية جديدة ليومك. اضغط لقراءتها واحفظها في مفضلتك.' end,'/messages#'||m.id::text,m.id,m.daily_verse_id);
 return new;
end; $$;
revoke all on function private.notify_message_recipient() from public,anon,authenticated;
drop trigger if exists notify_message_recipient on public.message_recipients;
create trigger notify_message_recipient after insert on public.message_recipients for each row execute function private.notify_message_recipient();

