create or replace function private.publish_daily_verse()
returns void language plpgsql security definer set search_path='' as $$
declare local_now timestamp; local_day date; chosen public.daily_verse_library%rowtype; verse_id uuid; message_id uuid;
begin
 local_now:=now() at time zone 'Africa/Cairo'; local_day:=local_now::date;
 if local_now::time<time '12:00' then return; end if;
 if exists(select 1 from public.daily_verses where verse_date=local_day) then return; end if;
 select l.* into chosen from public.daily_verse_library l where not exists(select 1 from public.daily_verses d where d.library_id=l.id and d.verse_date>=local_day-365) order by random() limit 1;
 if not found then select * into chosen from public.daily_verse_library order by random() limit 1; end if;
 if not found then return; end if;
 insert into public.daily_verses(library_id,verse_date,reference,verse_text) values(chosen.id,local_day,chosen.reference,chosen.verse_text) returning id into verse_id;
 insert into public.messages(title,body,daily_verse_id) values('آية اليوم',chosen.reference||E'\n'||chosen.verse_text,verse_id) returning id into message_id;
 insert into public.message_recipients(message_id,user_id) select message_id,id from public.profiles where role='member' and is_active=true on conflict do nothing;
end; $$;
revoke all on function private.publish_daily_verse() from public,anon,authenticated;

do $$ declare existing_job bigint; begin select jobid into existing_job from cron.job where jobname='aghapy-daily-verse'; if existing_job is not null then perform cron.unschedule(existing_job); end if; end $$;
select cron.schedule('aghapy-daily-verse','* * * * *','select private.publish_daily_verse();');

